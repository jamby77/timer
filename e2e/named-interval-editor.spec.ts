import { expect, test } from 'playwright/test'

test.use({ viewport: { width: 320, height: 640 }, isMobile: true, hasTouch: true })

test('round names fit the setup row, discard canceled edits and persist surviving rounds', async ({
  page,
}) => {
  await page.goto('/configure')
  await page.getByRole('heading', { name: 'Interval', exact: true }).tap()
  await page.locator('input[name=seconds]').first().pressSequentially('45')
  await page.locator('input[name=seconds]').last().pressSequentially('15')
  await page.getByLabel(/Timer Name/).fill('Named circuit')
  await page.getByLabel('Work Label', { exact: true }).fill('Lift')
  const count = page.getByLabel('Number of Intervals')
  const names = page.getByRole('button', { name: /Round names/i })
  await count.fill('')
  await expect(names).toBeDisabled()
  await count.fill('3')
  const shortHeight = (await names.boundingBox())!.height
  await count.fill('20')
  expect((await names.boundingBox())!.height).toBe(shortHeight)
  expect(shortHeight).toBeGreaterThanOrEqual(44)
  await names.tap()
  const dialog = page.getByRole('dialog', { name: /Round names/i })
  const field = (round: number) =>
    dialog.getByRole('textbox', { name: `Round ${round}`, exact: true })
  const cancel = dialog.getByRole('button', { name: 'Cancel', exact: true })
  const done = dialog.getByRole('button', { name: 'Done', exact: true })
  await expect(field(1)).toHaveAttribute('placeholder', 'Lift')
  await field(20).tap()
  await field(20).fill('Discard me')
  await expect(done).toBeInViewport({ ratio: 1 })
  await expect(cancel).toBeInViewport({ ratio: 1 })
  await cancel.tap()
  await names.tap()
  await expect(field(20)).toHaveValue('')
  await field(1).fill('Row')
  await field(20).fill('Ski')
  await done.tap()
  await expect(names).toContainText('2 of 20')
  await page.getByRole('button', { name: 'Save as Preset' }).tap()
  await expect(page.getByText('Preset saved.', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('heading', { name: 'Named circuit', exact: true }).tap()
  await names.tap()
  await expect(field(20)).toHaveValue('Ski')
  await expect(field(1)).toHaveValue('Row')
  await cancel.tap()
  await count.fill('3')
  await expect(names).toContainText('1 of 3')
  await page.getByLabel(/Timer Name/).fill('Short circuit')
  await page.getByRole('button', { name: 'Save as Preset' }).tap()
  await expect(page.getByText('Preset saved.', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('heading', { name: 'Short circuit', exact: true }).tap()
  await count.fill('20')
  await names.tap()
  await expect(field(1)).toHaveValue('Row')
  await expect(field(20)).toHaveValue('')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

test('EMOM keeps names when reopened with zero rest', async ({ page }) => {
  await page.goto('/configure')
  await page.getByRole('heading', { name: 'EMOM (10 min)', exact: true }).tap()
  const names = page.getByRole('button', { name: /Round names/i })
  await names.tap()
  const dialog = page.getByRole('dialog', { name: /Round names/i })
  const second = dialog.getByRole('textbox', { name: 'Round 2', exact: true })
  await second.fill('Bike')
  await dialog.getByRole('button', { name: 'Done' }).tap()
  await page.getByLabel(/Timer Name/).fill('Named EMOM')
  await page.getByRole('button', { name: 'Save as Preset' }).tap()
  await expect(page.getByText('Preset saved.', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('heading', { name: 'Named EMOM', exact: true }).tap()
  expect(Number(await page.locator('input[name=seconds]').last().inputValue())).toBe(0)
  await names.tap()
  await expect(second).toHaveValue('Bike')
})

test('Complex phase editor retains round names in the saved workout and its timeline', async ({
  page,
}) => {
  await page.goto('/configure/complex')
  await page.getByRole('button', { name: 'Add Phase', exact: true }).tap()
  await page.getByLabel('Phase type').tap()
  await page.getByRole('option', { name: /Interval/ }).tap()
  await page.getByLabel('Phase name').fill('Circuit')
  const names = page.getByRole('button', { name: /Round names/i })
  await names.tap()
  const dialog = page.getByRole('dialog', { name: /Round names/i })
  const second = dialog.getByRole('textbox', { name: 'Round 2', exact: true })
  await second.fill('Bike')
  await dialog.getByRole('button', { name: 'Done' }).tap()
  await page.getByRole('button', { name: 'Add', exact: true }).tap()
  await page.getByLabel(/Timer Name/).fill('Named workout')
  await page.getByRole('button', { name: 'Save as Preset' }).tap()
  await expect(page.getByText('Preset saved.', { exact: true })).toBeVisible()
  await page.goto('/configure')
  await page.getByRole('heading', { name: 'Named workout', exact: true }).tap()
  await page.getByRole('tab', { name: 'Preview', exact: true }).tap()
  const panel = page.getByRole('tabpanel', { name: 'Preview' })
  await panel.getByRole('button', { name: /Circuit/ }).tap()
  await expect(panel.getByText(/Round 2.*Bike/)).toBeVisible()
  await page.getByRole('button', { name: 'Edit phase' }).tap()
  await names.tap()
  await expect(second).toHaveValue('Bike')
})
