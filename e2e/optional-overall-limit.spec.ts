import { expect, test } from 'playwright/test'

test('clearing an overall limit saves and reopens an unlimited workout', async ({ page }) => {
  await page.goto('/configure/complex')
  await page.getByRole('button', { name: 'Add Phase', exact: true }).click()
  await page.getByLabel('Phase name').fill('Work')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByLabel('Timer Name*', { exact: true }).fill('Limited workout')
  const seconds = page.locator('input[name=seconds]')
  await seconds.press('ArrowUp')
  await expect(seconds).toHaveValue('01')
  await page.getByRole('button', { name: 'Save as Preset' }).click()
  await expect(page.getByText('Preset saved.', { exact: true })).toBeVisible()
  await page.getByLabel('Timer Name*', { exact: true }).fill('Unlimited workout')
  await seconds.press('ArrowDown')
  await expect(seconds).toHaveValue('00')
  await expect(page.getByRole('button', { name: 'Save as Preset' })).toBeEnabled()
  await page.getByRole('button', { name: 'Save as Preset' }).click()
  const presets = await page.evaluate(() =>
    Object.keys(localStorage)
      .filter((key) => key.startsWith('preset_'))
      .map((key) => JSON.parse(localStorage.getItem(key)!))
  )
  expect(presets.find((preset) => preset.name === 'Limited workout').config.overallTimeLimit).toBe(
    1
  )
  const unlimited = presets.find((preset) => preset.name === 'Unlimited workout')
  expect(unlimited).toBeDefined()
  expect(unlimited.config).not.toHaveProperty('overallTimeLimit')
  await page.goto('/configure')
  await page.reload()
  await page.getByRole('heading', { name: 'Unlimited workout', exact: true }).click()
  await expect(page.locator('input[name=seconds]')).toHaveValue('00')
  await page.getByRole('button', { name: 'Start Timer', exact: true }).click()
  await page.getByRole('button', { name: 'Start timer', exact: true }).click()
  await expect(page.locator('[data-timer-state]')).toHaveAttribute('data-timer-state', 'running')
  await expect(page.getByLabel('Overall workout time')).toHaveCount(0)
  await page.waitForTimeout(1300)
  await expect(page.getByRole('dialog', { name: 'Time Limit Reached' })).toBeHidden()
})
